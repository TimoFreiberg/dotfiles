import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import { execFileSync, spawn } from 'node:child_process';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { chromium } from 'playwright-core';
import { writeTaskPage, publishDocument } from '../src/document-page.mjs';
import { textHash } from '../src/save.mjs';
import { decodeSave } from '../src/save-message.mjs';
const root = path.resolve(import.meta.dirname, '..');
const require = createRequire(import.meta.url);
const { decode } = await import(require.resolve('@toon-format/toon'));

test('task browser: real save transport, rendered annotations, clean/dirty disk updates', { timeout: 120000 }, async t => {
  const dir = await mkdtemp(path.join(os.tmpdir(), 'lavish-task-browser-')), dist = path.join(dir, 'dist'); await mkdir(dist);
  execFileSync(process.execPath, [path.join(root, 'build.mjs'), root, dist]);
  const source = path.join(dir, 'task.md'); await writeFile(source, '---\ntitle: Hidden metadata\n---\n# Original\n\n- [x] Done\n\n<strong id="inline-html">Inline HTML</strong>\n');
  const { file } = await writeTaskPage(source, dist, { out: path.join(dir, 'page/index.html') });
  let browser, poll;
  t.after(async () => { poll?.kill(); if (browser) await browser.close(); try { execFileSync('lavish-axi', ['end', file], { stdio: 'ignore' }); } catch {} await rm(dir, { recursive: true, force: true }); });
  const output = execFileSync('lavish-axi', [file, '--no-open'], { encoding: 'utf8' }), url = output.match(/url:\s*"?(https?:\/\/[^"\s]+)/)?.[1]; assert.ok(url, output);
  browser = await chromium.launch({ executablePath: process.env.LAVISH_VIEW_CHROMIUM || chromium.executablePath(), headless: true });
  const page = await browser.newPage(), errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', route => ['localhost', '127.0.0.1', '[::1]'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort());
  await page.goto(url); const frame = page.locator('iframe').first().contentFrame(), editor = frame.getByRole('textbox', { name: 'Markdown text' });
  await editor.waitFor(); await frame.getByRole('status').filter({ hasText: 'Up to date with disk' }).waitFor();
  await frame.locator('body').evaluate(() => { window.__identity = Math.random(); }); const identity = await frame.locator('body').evaluate(() => window.__identity);
  await frame.getByRole('button', { name: 'Rendered', exact: true }).click();
  await frame.getByRole('heading', { name: /^Original/ }).waitFor();
  assert.ok(!(await frame.locator('#preview').innerText()).includes('Hidden metadata'));
  assert.equal(await frame.locator('#preview strong#inline-html').innerText(), 'Inline HTML');
  await page.locator('#annotation[aria-pressed="true"]').waitFor();
  await frame.getByRole('heading', { name: /^Original/ }).click();
  await frame.getByPlaceholder(/tell the agent/i).waitFor();
  await frame.getByRole('button', { name: 'Cancel', exact: true }).click();
  await frame.getByRole('button', { name: 'Edit', exact: true }).click();
  await writeFile(source, '# Clean update\n'); await publishDocument(file, source);
  await frame.getByRole('status').filter({ hasText: 'Up to date with disk' }).waitFor();
  await assertEventually(() => editor.inputValue(), '# Clean update\n');
  const mine = '# Mine\n\n' + ('Quotes " \\ \n\nContext data:\n{}\n</script>\u2028\u2029 雪 🦊\n').repeat(18000);
  assert.equal(await editor.isVisible(), true, 'Edit shows the textarea');
  await editor.fill('# Mine\n');
  // Playwright fill simulates typing; set the large paste in one input event.
  await editor.evaluate((node, text) => { node.value = text; node.dispatchEvent(new Event('input', { bubbles: true })); }, mine);
  await writeFile(source, '# External update\n'); await publishDocument(file, source);
  await frame.getByRole('button', { name: 'Keep mine', exact: true }).waitFor(); assert.equal(await editor.inputValue(), mine);
  await frame.getByRole('button', { name: 'Save', exact: true }).click();
  await frame.getByRole('status').filter({ hasText: 'Choose Reload' }).waitFor();
  await frame.getByRole('button', { name: 'Keep mine', exact: true }).click();
  poll = spawn('lavish-axi', ['poll', file, '--timeout-ms', '20000']); let polled = '', stderr = '';
  poll.stdout.setEncoding('utf8'); poll.stderr.setEncoding('utf8');
  poll.stdout.on('data', chunk => polled += chunk); poll.stderr.on('data', chunk => stderr += chunk);
  const done = new Promise((resolve, reject) => { poll.on('error', reject); poll.on('close', code => code === 0 ? resolve() : reject(new Error(stderr))); });
  await editor.press('Meta+s'); await done;
  const feedback = decode(polled), save = feedback.prompts.find(prompt => prompt.tag === 'lavish-view-save'); assert.ok(save, polled.slice(0, 1000));
  const decoded = decodeSave(save.prompt);
  assert.equal(decoded.baseHash, textHash('# External update\n'));
  let difference = 0; while (difference < mine.length && decoded.text[difference] === mine[difference]) difference++;
  assert.equal(textHash(decoded.text), textHash(mine), JSON.stringify({ actualLength: decoded.text.length, expectedLength: mine.length, difference, actual: decoded.text.slice(Math.max(0, difference - 20), difference + 80), expected: mine.slice(Math.max(0, difference - 20), difference + 80) }));
  assert.equal(save.data, undefined); assert.equal(await editor.inputValue(), mine);
  execFileSync('lavish-axi', ['reply', file, '--agent-reply', 'Conflict: test leaves edits on the page']);
  await writeFile(source, '# Another update\n'); await publishDocument(file, source);
  await frame.getByRole('button', { name: 'Reload (discard mine)', exact: true }).waitFor();
  await frame.getByRole('button', { name: 'Reload (discard mine)', exact: true }).click(); assert.equal(await editor.inputValue(), '# Another update\n');
  assert.equal(await frame.locator('body').evaluate(() => window.__identity), identity); assert.deepEqual(errors, []);
});
async function assertEventually(read, expected) {
  const deadline = Date.now() + 10000;
  while (Date.now() < deadline) { if (await read() === expected) return; await new Promise(resolve => setTimeout(resolve, 50)); }
  assert.equal(await read(), expected);
}
